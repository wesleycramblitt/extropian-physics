bool PolarDatabase::load_csv(const std::string& path)
{
    std::ifstream file(path);
    if (!file) return false;

    std::string line;
    bool header_seen = false;
    std::size_t name_idx = 0, re_idx = 1, alpha_idx = 2, cl_idx = 3, cd_idx = 4;

    std::string current_name;
    double current_re = 0.0;
    std::vector<double> alphas, cls, cds;

    auto flush = [&](const std::string& name, double re)
    {
        if (!name.empty() && alphas.size() >= 2)
        {
            AirfoilPolar p;
            p.name = name;
            p.re = re;
            p.alpha_deg = std::move(alphas);
            p.cl = std::move(cls);
            p.cd = std::move(cds);
            add(std::move(p));
        }
        alphas.clear();
        cls.clear();
        cds.clear();
    };

    while (std::getline(file, line))
    {
        std::string t = trim(line);
        if (t.empty()) continue;
        if (t.front() == '#') continue;

        auto cols = split_csv(t);
        if (!header_seen)
        {
            for (auto& c : cols) std::transform(c.begin(), c.end(), c.begin(),
                [](unsigned char ch){ return static_cast<char>(std::tolower(ch)); });
            for (std::size_t i = 0; i < cols.size(); ++i)
            {
                if (cols[i] == "name") name_idx = i;
                else if (cols[i] == "re") re_idx = i;
                else if (cols[i] == "alpha_deg") alpha_idx = i;
                else if (cols[i] == "cl") cl_idx = i;
                else if (cols[i] == "cd") cd_idx = i;
            }
            header_seen = true;
            continue;
        }

        if (cols.size() < 5) continue;
        try
        {
            const std::string name = cols[name_idx];
            const double re = std::stod(cols[re_idx]);
            const double alpha = std::stod(cols[alpha_idx]);
            const double cl = std::stod(cols[cl_idx]);
            const double cd = std::stod(cols[cd_idx]);

            if (name != current_name || std::fabs(re - current_re) > 1e-9)
            {
                flush(current_name, current_re);
                current_name = name;
                current_re = re;
            }
            alphas.push_back(alpha);
            cls.push_back(cl);
            cds.push_back(cd);
        }
        catch (...)
        {
            // Gracefully skip malformed rows.
            continue;
        }
    }
    flush(current_name, current_re);
    return header_seen;
}

bool PolarDatabase::load_directory(const std::string& path)
{
    bool any = false;
    if (!std::filesystem::is_directory(path)) return false;
    for (const auto& entry : std::filesystem::directory_iterator(path))
    {
        if (!entry.is_regular_file()) continue;
        const auto ext = entry.path().extension().string();
        if (ext != ".csv" && ext != ".CSV") continue;
        if (load_csv(entry.path().string())) any = true;
    }
    return any;
}

